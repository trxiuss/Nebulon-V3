function resolveLocale(request) {
  const cookie = request?.headers?.get?.("cookie") || "";
  const savedLocale = cookie.match(/(?:^|;\s*)nebulon-locale=(tr|en)(?:;|$)/)?.[1];
  if (savedLocale) return savedLocale;
  const country = (request?.headers?.get?.("cf-ipcountry") || request?.headers?.get?.("x-vercel-ip-country") || "").toUpperCase();
  return country === "TR" || country === "AZ" ? "tr" : "en";
}

export function apiMessage(request, key) {
  const locale = resolveLocale(request);
  return API_MESSAGES[locale][key] || API_MESSAGES.tr[key] || key;
}
